// Modify only a disposable copy: never touch the editing data or the normal dist.
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import assert from 'node:assert/strict';
import { load } from 'cheerio';
import { topics } from '../src/lib/data-node.mjs';
fs.mkdirSync('test-results',{recursive:true});
const fixture=fs.mkdtempSync(path.resolve('test-results/propagation-'));
const data=path.join(fixture,'data'),output=path.join(fixture,'dist');
fs.cpSync('src/data',data,{recursive:true});
const topic=structuredClone(topics[0]);
const day=topic.sessions[0].startsAt.slice(0,10);
topic.sessions[0].startsAt=day+'T20:15:00+09:00';
topic.sessions[0].endsAt=day+'T21:15:00+09:00';
topic.sessions[0].guest='日程同期検証ゲスト';
fs.writeFileSync(path.join(data,'topics',topic.slug+'.json'),JSON.stringify(topic,null,2));
fs.writeFileSync(path.join(data,'archives.json'),JSON.stringify([{id:'verification-video',title:'公開動画の生成検証',publishedAt:'2026-10-06',videoUrl:'https://www.youtube.com/watch?v=dQw4w9WgXcQ',description:'テスト専用・公開しない'}]));
const result=spawnSync(process.execPath,['node_modules/astro/bin/astro.mjs','build'],{env:{...process.env,ASTRO_TELEMETRY_DISABLED:'1',KD_DATA_DIR:data,KD_BUILD_DIR:output},encoding:'utf8'});
if(result.status!==0)throw new Error(result.error?.message||result.stdout+'\n'+result.stderr);
const read=route=>load(fs.readFileSync(path.join(output,route),'utf8'));
const home=read('index.html'),list=read('topics.html'),detail=read('topics/'+topic.slug+'.html');
assert.ok(home(`.topic-teasers a[href="/topics/${topic.slug}.html"]`).text().includes('20:15頃〜21:15頃'));
const countdown=JSON.parse(home('#kd-sessions-data').text());
assert.equal(countdown[0].start,Date.parse(topic.sessions[0].startsAt));
assert.equal(countdown[0].end,Date.parse(topic.sessions[0].endsAt));
const card=list('[data-topic-card]').filter((_,el)=>list(el).find('h2 a').attr('href')==='/topics/'+topic.slug+'.html');
assert.ok(card.text().includes('20:15頃〜21:15頃'));
assert.ok(card.attr('data-search').includes('日程同期検証ゲスト'));
assert.ok(detail('.broadcast-schedule li').first().text().includes('20:15頃〜21:15頃'));
assert.ok(detail('.broadcast-schedule li').first().text().includes('日程同期検証ゲスト'));
const archive=read('archives.html');
assert.equal(archive('.archive-grid').length,1);
assert.equal(archive('.archive-card').length,1);
assert.equal(archive('.archive-empty').length,0);
assert.equal(archive('[data-archive-count]').text(),'1本の公開動画');
assert.equal(archive('.archive-player iframe').length,0);
assert.equal(archive('[data-archive-player-src]').attr('data-archive-player-src'),'https://www.youtube-nocookie.com/embed/dQw4w9WgXcQ?autoplay=0&rel=0');
fs.writeFileSync('test-results/propagation-latest.json',JSON.stringify({output}));
assert.deepEqual(JSON.parse(fs.readFileSync('src/data/topics/'+topic.slug+'.json','utf8')),topics[0]);
console.log('One-session change propagated to homepage, countdown, list, detail and search. Nonempty archive generation passed. Source data unchanged.');
